"""
Write LaTeX fragments for the delivery tables of the black hole paper from the output of gen_mvm_v2_delivery.py.

Usage: python make_delivery_tables.py <dir with mvm_v2_delivery_M*.json> <output .tex>
Fragments (tabular bodies only, in the layout of the paper's tab:gmap and tab:reach):
  gmap   growth factor of a 1e3 Msun seed, 3e10 and 3e11 Msun side by side (as tab:gmap), then 3e13 Msun
  reach  critical seed with its ratio to the fiducial cell and the final M_BH/M_* of fixed seeds (as tab:reach), 3e10 and 3e11,
         then 3e13 Msun
"""
import json
import sys
from pathlib import Path

import numpy as np

d, outpath = Path(sys.argv[1]), Path(sys.argv[2])
R = {k: json.load(open(d / f"mvm_v2_delivery_M{i:02d}.json")) for k, i in (("3e10", 0), ("3e11", 4), ("3e13", 12))}


def g3(x):
    """Three significant figures, no exponent, as in the paper's growth-factor table."""
    if x < 2:
        return "%.2f" % x
    if x < 10:
        return "%.1f" % x
    return "%d" % float("%.3g" % x) if x < 1000 else "%d" % int(round(x, -int(np.floor(np.log10(x))) + 2))


def sci(x):
    m, e = ("%.1e" % x).split("e")
    return r"$%s\times10^{%d}$" % (m, int(e))


def ratio(x):
    return ("%.2f" % x) if x >= 0.1 else sci(x)


lines = ["%% generated by make_delivery_tables.py from %s" % d, "%% ---- growth factor G of a 1e3 Msun seed (median over %d trees) ----" % R["3e10"]["gmap"]["n_trees"]]
Rn = R["3e10"]["gmap"]["Rnuc"]
lines.append(r"$\Rnuc$ [pc] $\rightarrow$ & " + " & ".join("%d" % r for r in Rn) + r" & & " + " & ".join("%d" % r for r in Rn) + r" \\")
lines.append(r"\hline")
for i, s in enumerate(R["3e10"]["gmap"]["sigma"]):
    a = " & ".join(g3(c[1]) for c in R["3e10"]["gmap"]["G_p16_p50_p84"][i])
    b = " & ".join(g3(c[1]) for c in R["3e11"]["gmap"]["G_p16_p50_p84"][i])
    lines.append(r"$\sigma_j=%.1f$ & %s & & %s \\" % (s, a, b))
lines += ["", "% ---- same, 3e13 Msun ----"]
lines.append(r"$\Rnuc$ [pc] $\rightarrow$ & " + " & ".join("%d" % r for r in Rn) + r" \\")
lines.append(r"\hline")
for i, s in enumerate(R["3e13"]["gmap"]["sigma"]):
    lines.append(r"$\sigma_j=%.1f$ & %s \\" % (s, " & ".join(g3(c[1]) for c in R["3e13"]["gmap"]["G_p16_p50_p84"][i])))


def reach_rows(keys):
    out = []
    ncell = len(R[keys[0]]["reach"]["cells"])
    for ci in range(ncell):
        parts = []
        for k in keys:
            c = R[k]["reach"]["cells"][ci]
            base = np.nanmedian(R[k]["reach"]["cells"][0]["Mcrit"])
            m = np.nanmedian(c["Mcrit"])
            fid = "" if ci else " fiducial"
            rr = [np.nanmedian(c["ratio"][s]) for s in ("1000.0", "200000.0", "10000000.0")]
            parts.append(" & ".join([sci(m) + " (%.2f)" % (m / base)] + [ratio(x) for x in rr]))
        c0 = R[keys[0]]["reach"]["cells"][ci]
        out.append("(%.1f, %d)%s & %s \\\\" % (c0["sigma_lnj"], c0["R_nuc_pc"], "" if ci else " fiducial", (" & & ").join(parts)))
    return out


lines += ["", "%% ---- reach table, %d trees per cell, 3e10 | 3e11 ----" % R["3e10"]["reach"]["n_trees"]] + reach_rows(["3e10", "3e11"])
lines += ["", "% ---- reach table, 3e13 ----"] + reach_rows(["3e13"])
outpath.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
